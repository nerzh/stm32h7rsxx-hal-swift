  func testPCDAndHCDCallerOwnedStorage() {
    let words = UnsafeMutableBufferPointer<UInt32>.allocate(capacity: 12)
    let configuration = UnsafeMutableBufferPointer<UInt8>.allocate(capacity: 13)
    let input = UnsafeMutableBufferPointer<UInt32>.allocate(capacity: 208)
    let output = UnsafeMutableBufferPointer<UInt32>.allocate(capacity: 208)
    let channels = UnsafeMutableBufferPointer<UInt32>.allocate(capacity: 432)
    let buffers = UnsafeMutableBufferPointer<UnsafeMutablePointer<UInt8>?>.allocate(capacity: 48)
    let setup = UnsafeMutableBufferPointer<UInt32>.allocate(capacity: 12)
    words.initialize(repeating: 0)
    configuration.initialize(repeating: 0)
    input.initialize(repeating: 0)
    output.initialize(repeating: 0)
    channels.initialize(repeating: 0)
    buffers.initialize(repeating: nil)
    setup.initialize(repeating: 0)
    defer {
      words.deallocate()
      configuration.deallocate()
      input.deallocate()
      output.deallocate()
      channels.deallocate()
      buffers.deallocate()
      setup.deallocate()
    }
    let p = STM32PCDHandleRegisters(
      words: .init(rebasing: words[0..<9]), configuration: configuration, inEndpoints: input,
      outEndpoints: output, inBuffers: .init(rebasing: buffers[0..<16]),
      outBuffers: .init(rebasing: buffers[16..<32]), setup: setup)
    let h = STM32HCDHandleRegisters(
      words: .init(rebasing: words[9..<12]), configuration: configuration, channels: channels,
      buffers: .init(rebasing: buffers[32..<48]))
    for field in PCDHandleWord.allCases {
      p.write(field, value: 0xFEDC_BA98)
      XCTAssertEqual(p.read(field), field == .address ? 0x98 : 0xFEDC_BA98)
    }
    for field in HCDHandleWord.allCases {
      h.write(field, value: 0x1234_5678)
      XCTAssertEqual(h.read(field), 0x1234_5678)
    }
    for field in USBConfigurationField.allCases {
      p.writeConfiguration(field, value: UInt8(field.rawValue))
      XCTAssertEqual(h.readConfiguration(field), UInt8(field.rawValue))
    }
    for i: UInt32 in 0..<16 {
      p.endpoint(i, isIn: true).write(.transferLength, value: i + 1)
      p.endpoint(i, isIn: false).write(.transferLength, value: i + 101)
      h.channel(i).write(.transferLength, value: i + 201)
      XCTAssertEqual(input[Int(i) * 13 + 7], i + 1)
      XCTAssertEqual(output[Int(i) * 13 + 7], i + 101)
      XCTAssertEqual(channels[Int(i) * 27 + 17], i + 201)
      let b = UnsafeMutablePointer<UInt8>(bitPattern: UInt(0x2400_0000 + i * 64))!
      p.endpoint(i, isIn: true).writeBuffer(b)
      p.endpoint(i, isIn: false).writeBuffer(b + 1)
      h.channel(i).writeBuffer(b + 2)
      XCTAssertEqual(buffers[Int(i)], b)
      XCTAssertEqual(buffers[Int(i) + 16], b + 1)
      XCTAssertEqual(buffers[Int(i) + 32], b + 2)
    }
    p.setupBuffer()[47] = 0xA5
    XCTAssertEqual(setup[11], 0xA500_0000)
  }
  func testCallbackStorageAndVolatileDelay() {
    let storage = UnsafeMutableBufferPointer<UInt>.allocate(capacity: 25)
    storage.initialize(repeating: 0)
    defer { storage.deallocate() }
    storage[0] = 123
    storage[24] = 456
    let p = STM32PCDCallbackRegisters(storage: .init(rebasing: storage[1..<16]))
    let h = STM32HCDCallbackRegisters(storage: .init(rebasing: storage[16..<24]))
    let callback: USBCallback = { _ in }
    let endpoint: USBEndpointCallback = { _, _ in }
    let message: USBMessageCallback = { _, _ in }
    let urb: HCDURBCallback = { _, _, _ in }
    for id in PCDCallbackID.allCases {
      p.write(id, value: callback)
      XCTAssertEqual(
        unsafeBitCast(p.read(id)!, to: UInt.self), unsafeBitCast(callback, to: UInt.self))
    }
    for id in PCDEndpointCallbackID.allCases {
      p.writeEndpoint(id, value: endpoint)
      XCTAssertEqual(
        unsafeBitCast(p.readEndpoint(id)!, to: UInt.self), unsafeBitCast(endpoint, to: UInt.self))
    }
    for id in PCDMessageCallbackID.allCases {
      p.writeMessage(id, value: message)
      XCTAssertEqual(
        unsafeBitCast(p.readMessage(id)!, to: UInt.self), unsafeBitCast(message, to: UInt.self))
    }
    for id in HCDCallbackID.allCases {
      h.write(id, value: callback)
      XCTAssertEqual(
        unsafeBitCast(h.read(id)!, to: UInt.self), unsafeBitCast(callback, to: UInt.self))
    }
    h.writeURB(urb)
    XCTAssertEqual(unsafeBitCast(h.readURB()!, to: UInt.self), unsafeBitCast(urb, to: UInt.self))
    p.write(.mspInitialize, value: nil)
    p.writeEndpoint(.dataOut, value: nil)
    p.writeMessage(.batteryCharging, value: nil)
    h.writeURB(nil)
    XCTAssertNil(p.read(.mspInitialize))
    XCTAssertNil(p.readEndpoint(.dataOut))
    XCTAssertNil(p.readMessage(.batteryCharging))
    XCTAssertNil(h.readURB())
    XCTAssertEqual(storage[0], 123)
    XCTAssertEqual(storage[24], 456)
    STM32USBRegisters(.highSpeed).delayAfterAHBIdle()
  }
