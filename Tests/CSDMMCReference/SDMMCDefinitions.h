uint32_t CSDMMC_ReadVolatile(volatile const uint32_t *);
void CSDMMC_WriteVolatile(volatile uint32_t *,uint32_t);
#define SystemCoreClock CSDMMC_CoreClock()
#define READ_REG(r) CSDMMC_ReadVolatile(&(r))
#define WRITE_REG(r,v) CSDMMC_WriteVolatile(&(r),(v))
#define READ_BIT(r,b) (READ_REG(r)&(b))
#define SET_BIT(r,b) WRITE_REG(r,READ_REG(r)|(b))
#define CLEAR_BIT(r,b) WRITE_REG(r,READ_REG(r)&~(b))
#define CLEAR_REG(r) WRITE_REG(r,0)
#define MODIFY_REG(r,c,s) WRITE_REG(r,(READ_REG(r)&~(c))|(s))
#undef __SDMMC_CMDSTOP_ENABLE
#define __SDMMC_CMDSTOP_ENABLE(r) SET_BIT((r)->CMD,SDMMC_CMD_CMDSTOP)
#undef __SDMMC_CMDSTOP_DISABLE
#define __SDMMC_CMDSTOP_DISABLE(r) CLEAR_BIT((r)->CMD,SDMMC_CMD_CMDSTOP)
#undef __SDMMC_CMDTRANS_ENABLE
#define __SDMMC_CMDTRANS_ENABLE(r) SET_BIT((r)->CMD,SDMMC_CMD_CMDTRANS)
#undef __SDMMC_CMDTRANS_DISABLE
#define __SDMMC_CMDTRANS_DISABLE(r) CLEAR_BIT((r)->CMD,SDMMC_CMD_CMDTRANS)
#undef __SDMMC_SUSPEND_CMD_ENABLE
#define __SDMMC_SUSPEND_CMD_ENABLE(r) SET_BIT((r)->CMD,SDMMC_CMD_CMDSUSPEND)
#undef __SDMMC_SUSPEND_CMD_DISABLE
#define __SDMMC_SUSPEND_CMD_DISABLE(r) CLEAR_BIT((r)->CMD,SDMMC_CMD_CMDSUSPEND)
#undef __SDMMC_START_READWAIT_ENABLE
#define __SDMMC_START_READWAIT_ENABLE(r) SET_BIT((r)->DCTRL,SDMMC_DCTRL_RWSTART)
#undef __SDMMC_START_READWAIT_DISABLE
#define __SDMMC_START_READWAIT_DISABLE(r) CLEAR_BIT((r)->DCTRL,SDMMC_DCTRL_RWSTART)
#undef __SDMMC_STOP_READWAIT_ENABLE
#define __SDMMC_STOP_READWAIT_ENABLE(r) SET_BIT((r)->DCTRL,SDMMC_DCTRL_RWSTOP)
#undef __SDMMC_STOP_READWAIT_DISABLE
#define __SDMMC_STOP_READWAIT_DISABLE(r) CLEAR_BIT((r)->DCTRL,SDMMC_DCTRL_RWSTOP)
#undef __SDMMC_OPERATION_ENABLE
#define __SDMMC_OPERATION_ENABLE(r) SET_BIT((r)->DCTRL,SDMMC_DCTRL_SDIOEN)
#undef __SDMMC_OPERATION_DISABLE
#define __SDMMC_OPERATION_DISABLE(r) CLEAR_BIT((r)->DCTRL,SDMMC_DCTRL_SDIOEN)
#endif
