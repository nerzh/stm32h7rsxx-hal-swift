            CECFlags.receiveOverrun.rawValue,
            CECFlags.bitRisingError.rawValue,
            CECFlags.shortBitPeriodError.rawValue,
            CECFlags.longBitPeriodError.rawValue,
            CECFlags.receiveAcknowledgeError.rawValue,
            CECFlags.arbitrationLost.rawValue,
            CECFlags.transmitByte.rawValue,
            CECFlags.transmitEnd.rawValue,
            CECFlags.transmitUnderrun.rawValue,
            CECFlags.transmitError.rawValue,
            CECFlags.transmitAcknowledgeError.rawValue,
            CECInterrupts.receiveByte.rawValue,
