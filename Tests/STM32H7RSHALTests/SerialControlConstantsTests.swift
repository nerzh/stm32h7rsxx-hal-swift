            MDIOSError.timeout.rawValue,
            MDIOSError.data.rawValue,
            MDIOSError.invalidCallback.rawValue,
            CECState.reset.rawValue,
            CECState.ready.rawValue,
            CECState.busy.rawValue,
            CECState.busyReceive.rawValue,
