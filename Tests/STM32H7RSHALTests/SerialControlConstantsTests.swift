            CECInterrupts.receiveOverrun.rawValue,
            CECInterrupts.bitRisingError.rawValue,
            CECInterrupts.shortBitPeriodError.rawValue,
            CECInterrupts.longBitPeriodError.rawValue,
            CECInterrupts.receiveAcknowledgeError.rawValue,
            CECInterrupts.arbitrationLost.rawValue,
            CECInterrupts.transmitByte.rawValue,
